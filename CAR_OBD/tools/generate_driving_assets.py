#!/usr/bin/env python3
"""Generate the approved driving-page assets; Pillow is only needed for regeneration."""
from pathlib import Path
import math
from hashlib import sha256
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
FONT=ROOT/'assets/fonts/roboto-condensed/RobotoCondensed.ttf'
S=4
OUT=ROOT/'src/display/DrivingAssets.h'
lines=['#pragma once','#include <cstdint>', '// Generated by tools/generate_driving_assets.py.', '// Roboto Condensed Bold, Copyright 2011 The Roboto Project Authors.', '// SIL OFL 1.1: assets/fonts/roboto-condensed/OFL.txt.', f'// Source SHA256: {sha256(FONT.read_bytes()).hexdigest()}','namespace drivingassets {','struct Mask { int x,y,w,h; const uint8_t* data; };','struct Glyph { char ch; int advance; Mask mask; };','struct Font { const Glyph* glyphs; unsigned count; int height; };']
def font(size):
 f=ImageFont.truetype(str(FONT),size*S);f.set_variation_by_axes([700]);return f
def array(name,data,kind='uint8_t',hexwidth=2):
 lines.append(f'constexpr {kind} {name}[] = {{')
 for i in range(0,len(data),24):lines.append(' '+','.join(f'0x{x:0{hexwidth}x}' for x in data[i:i+24])+',')
 lines.append('};')
def mask(name,image,x=0,y=0):
 if image.mode!='L':image=image.getchannel('A')
 w,h=image.size
 if w*h%2:image=Image.new('L',(w+1,h));raise ValueError('even pixel count required')
 p=list(image.point(lambda v:(v*15+127)//255).get_flattened_data());array(name+'Data',[(p[i]<<4)|p[i+1] for i in range(0,len(p),2)])
 lines.append(f'constexpr Mask {name}{{{x},{y},{w},{h},{name}Data}};')
def tightmask(name,image):
 image=image.getchannel('A') if image.mode!='L' else image
 box=image.getbbox();assert box
 x,y,x1,y1=box
 if (x1-x)*(y1-y)%2:x1+=1
 mask(name,image.crop((x,y,x1,y1)),x,y)
def label(d,text,cx,y,size,color):
 f=font(size);b=d.textbbox((0,0),text,font=f);d.text((cx*S-(b[2]-b[0])/2-b[0],y*S-b[1]),text,font=f,fill=color)
def point(a,r):a=math.radians(a);return((120+r*math.cos(a))*S,(120+r*math.sin(a))*S)
def curved(im,text,angle,color):
 f=font(13);spacing=.35*S;adv=[f.getlength(c) for c in text];cursor=-(sum(adv)+spacing*(len(text)-1))/2
 for ch,a in zip(text,adv):
  theta=angle+math.degrees((cursor+a/2)/(88*S));b=f.getbbox(ch)
  tile=Image.new('RGBA',(b[2]-b[0]+6*S,b[3]-b[1]+6*S));ImageDraw.Draw(tile).text((3*S-b[0],3*S-b[1]),ch,font=f,fill=(*color,255))
  rot=tile.rotate(-(theta+90),resample=Image.Resampling.BICUBIC,expand=True);x,y=point(theta,88)
  im.paste(rot,(round(x-rot.width/2),round(y-rot.height/2)),rot);cursor+=a+spacing
for day in (False,True):
 bg=(255,255,255) if day else (0,0,0);muted=(70,80,90) if day else (128,150,163)
 load=(0,115,105) if day else (44,211,194);throttle=(0,90,190) if day else (77,161,255)
 im=Image.new('RGB',(240*S,240*S),bg);d=ImageDraw.Draw(im)
 for side in ('left','right'):
  for p in (0,25,50,75,100):
   angle=180+p/100*86 if side=='left' else 360-p/100*86;d.line([point(angle,97),point(angle,100)],fill=muted,width=S)
 label(d,'100',101,26,9,muted);label(d,'100',139,26,9,muted)
 curved(im,'LOAD',230,load);curved(im,'THROTTLE',310,throttle)
 label(d,'0',27,123,9,muted);label(d,'0',213,123,9,muted)
 label(d,'KM/H',120,145,11,muted);label(d,'COOLANT',48,164,8,muted);label(d,'VOLTAGE',192,164,8,muted)
 im=im.resize((240,240),Image.Resampling.LANCZOS)
 pixels=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in im.get_flattened_data()]
 array('kDayBase' if day else 'kNightBase',pixels,'uint16_t',4)
# Cache curved arc coverage in flash, avoiding trigonometry on the ESP32.
arcNames=[]
for side in ('left','right'):
 for n in range(30):
  image=Image.new('L',(240*S,240*S));d=ImageDraw.Draw(image)
  start=180+n/30*86 if side=='left' else 360-n/30*86
  end=180+(n+.86)/30*86 if side=='left' else 360-(n+.86)/30*86
  points=[point(start+t*(end-start)/5,112) for t in range(6)]+[point(end-t*(end-start)/5,103) for t in range(6)]
  d.polygon(points,fill=255)
  name=f'kArc{len(arcNames)}';tightmask(name,image.resize((240,240),Image.Resampling.LANCZOS));arcNames.append(name)
lines.append('constexpr Mask kArcs[] = {'+','.join(arcNames)+'};')
for size,chars in [(19,'0123456789%.-'),(20,'0123456789.-'),(24,'0123456789-')]:
 f=font(size);top=min(f.getbbox(c)[1] for c in chars);bottom=max(f.getbbox(c)[3] for c in chars);h=math.ceil((bottom-top)/S);names=[]
 for idx,ch in enumerate(chars):
  advance=f.getlength(ch);w=math.ceil(advance/S)
  if w*h%2:w+=1
  im=Image.new('L',(w*S,h*S));ImageDraw.Draw(im).text((0,-top),ch,font=f,fill=255)
  name=f'kF{size}G{idx}';mask(name,im.resize((w,h),Image.Resampling.LANCZOS));names.append((ch,round(advance/S*256),name))
 lines.append(f'constexpr Glyph kGlyphs{size}[] = {{')
 for ch,a,name in names:lines.append(f" {{'{ch}',{a},{name}}},")
 lines.append('};');lines.append(f'constexpr Font kFont{size}{{kGlyphs{size},{len(names)},{h}}};')
for text in ('P','R','N','D','D1','D2','D3','D4','D5','D6','--'):
 im=Image.new('RGBA',(240*S,240*S));label(ImageDraw.Draw(im),text,120,177 if text=='--' else 163,39,(255,255,255));tightmask('kGear'+('Unknown' if text=='--' else text),im.resize((240,240),Image.Resampling.LANCZOS))
for text,size,name in [('C',9,'kC'),('V',9,'kV'),('RPM',8,'kRpmUnit')]:
 f=font(size);b=f.getbbox(text);w=math.ceil((b[2]-b[0])/S);h=math.ceil((b[3]-b[1])/S)
 if w*h%2:w+=1
 im=Image.new('L',(w*S,h*S));ImageDraw.Draw(im).text((-b[0],-b[1]),text,font=f,fill=255);mask(name,im.resize((w,h),Image.Resampling.LANCZOS))
# Hollow Check Engine outline, exactly the approved 4.7x geometry.
im=Image.new('L',(240*S,240*S));d=ImageDraw.Draw(im);scale=4.7;ox=120-21*scale;oy=112-16*scale
xy=lambda p:((ox+p[0]*scale)*S,(oy+p[1]*scale)*S)
paths=[[(7,9),(12,9),(12,6),(26,6),(32,12),(36,12),(36,9),(40,9),(40,27),(36,27),(36,24),(32,24),(27,30),(12,30),(7,25),(7,9)],[(17,2),(25,2)],[(21,2),(21,6)],[(2,12),(2,24)],[(2,18),(7,18)]]
for path in paths:
 d.line([xy(p) for p in path],fill=255,width=round(2.1*scale*S),joint='curve')
 for p in path:
  x,y=xy(p);r=1.05*scale*S;d.ellipse((x-r,y-r,x+r,y+r),fill=255)
tightmask('kMilOutline',im.resize((240,240),Image.Resampling.LANCZOS))
lines.append('} // namespace drivingassets');OUT.write_text('\n'.join(lines)+'\n');print(OUT)
