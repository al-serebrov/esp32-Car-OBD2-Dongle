#!/usr/bin/env python3
"""Generate flash-resident, 4-bit alpha speed digits using Pillow/FreeType.

Source font and OFL license live in assets/fonts/roboto-condensed. Pillow is
needed only for regeneration; normal PlatformIO builds use the checked-in header.
"""
from pathlib import Path
from hashlib import sha256
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/fonts/roboto-condensed/RobotoCondensed.ttf'
DEST = ROOT / 'src/display/SpeedFont.h'
PROFILES = ((56, 120), (48, 104), (42, 88), (36, 76))
SUPERSAMPLE = 4


def render_profile(width, height):
    font = ImageFont.truetype(str(SOURCE), 164 * SUPERSAMPLE)
    font.set_variation_by_axes([700])
    boxes = [font.getbbox(str(n)) for n in range(10)]
    top, bottom = min(box[1] for box in boxes), max(box[3] for box in boxes)
    advance = max(round(font.getlength(str(n))) for n in range(10))
    lefts, glyphs = [], []
    for number in range(10):
        canvas = Image.new('L', (advance, bottom - top))
        ImageDraw.Draw(canvas).text((0, -top), str(number), font=font, fill=255)
        canvas = canvas.resize((width, height), Image.Resampling.LANCZOS)
        quantized = canvas.point(lambda value: (value * 15 + 127) // 255)
        bounds = quantized.getbbox()
        assert bounds is not None
        # Align all ink right edges. Only the leading glyph affects centering;
        # trailing digit changes retain identical tabular cell positions.
        cropped = quantized.crop((bounds[0], 0, bounds[2], height))
        aligned = Image.new('L', (width, height))
        aligned.paste(cropped, (width - cropped.width, 0))
        lefts.append(width - cropped.width)
        pixels = aligned.tobytes()
        glyphs.append(bytes((pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2)))

    return lefts, glyphs


def main():
    lines = [
        '#pragma once', '#include <cstdint>', '',
        '// Generated by tools/generate_speed_font.py; do not edit by hand.',
        '// Roboto Condensed Bold, Copyright 2011 The Roboto Project Authors.',
        '// SIL Open Font License 1.1: assets/fonts/roboto-condensed/OFL.txt.',
        f'// Source SHA256: {sha256(SOURCE.read_bytes()).hexdigest()}',
        'namespace speedfont {',
        'struct Font { int width, height; const uint8_t* inkLeft; const uint8_t* alpha; };',
    ]
    total = 0
    for index, (width, height) in enumerate(PROFILES):
        lefts, glyphs = render_profile(width, height)
        lines.append(f'constexpr uint8_t kInkLeft{index}[10] = {{' + ', '.join(map(str, lefts)) + '};')
        lines.append(f'constexpr uint8_t kAlpha{index}[10][{width * height // 2}] = {{')
        for number, glyph in enumerate(glyphs):
            lines.append(f'    {{ // {number}')
            for i in range(0, len(glyph), 24):
                lines.append('        ' + ','.join(f'0x{value:02x}' for value in glyph[i:i + 24]) + ',')
            lines.append('    },')
        lines.append('};')
        total += sum(map(len, glyphs))
        print(f'{height}px digits: leading insets {lefts}')
    lines.append('constexpr Font kFonts[] = {')
    for index, (width, height) in enumerate(PROFILES):
        lines.append(f'    {{{width}, {height}, kInkLeft{index}, &kAlpha{index}[0][0]}},')
    lines.extend(['};', '}  // namespace speedfont', ''])
    DEST.write_text('\n'.join(lines))
    print(f'Generated {DEST.relative_to(ROOT)}: {total} alpha bytes')


if __name__ == '__main__':
    main()
